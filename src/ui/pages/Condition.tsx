import "./pages-cp.css";
import { useState } from "react";
import { Check, Copy, Printer, SlidersHorizontal } from "lucide-react";
import { Button, Card, PageHeader, Row } from "../primitives";
import { HANOVER } from "../model";
import { dateLabel, fixed, int, mgal, mgd, pctChange, signed } from "../format";
import { useWorkspace } from "../workspace";

export function Condition() {
  const { s, set, m } = useWorkspace();
  const [copied, setCopied] = useState(false);
  const { campus, hybrid, plan, capGal, peakLimitMW, year } = m;

  const capText = int(capGal);
  const peakText = fixed(peakLimitMW, 1);
  const ratio = hybrid.avgDayGal > 0 ? fixed(hybrid.maxDayGal / hybrid.avgDayGal, 1) : "n/a";
  const cut = hybrid.maxDayGal > 0 ? Math.round((1 - plan.maxDayGal / hybrid.maxDayGal) * 100) : 0;
  const hybridDate = dateLabel(year, hybrid.maxDay);
  // Headroom before any campus demand: what the system has left on its own peak day.
  const spare = m.supply - HANOVER.peakUse;
  const shareOfSpare = spare > 0 ? Math.round((plan.maxDayGal / spare) * 100) : null;

  const clauses = [
    `Cooling water use shall not exceed ${capText} gallons on any calendar day.`,
    "Daily cooling water use shall be metered and reported to the County monthly.",
    `The facility shall not exceed a peak electrical demand of ${peakText} MW to meet the limit in condition 1.`,
    "During a declared water emergency, cooling shall run in dry mode.",
  ];
  const basis =
    `On measured ${year} weather at Hanover County Municipal Airport, the adiabatic hybrid design's worst day is ` +
    `${mgd(hybrid.maxDayGal)} million gallons on ${hybridDate}, ${ratio}× its average day. Scheduling the same ` +
    `${mgal(hybrid.annualGal)} million gallons a year under a ${capText} gallon daily cap lowers the worst day by ${cut}% ` +
    `with no increase in peak power.`;
  const county =
    "Hanover suburban supply 24.775 MGD (Richmond 20, Doswell 4.0, Henrico 0.775); peak use about 11.7 MGD." +
    (shareOfSpare !== null
      ? ` On the worst day the capped campus would use ${shareOfSpare}% of the remaining ${mgd(spare)} MGD of headroom.`
      : "");
  const shortfall = s.richmondDown
    ? `With the Richmond contract offline the system is short ${mgd(-spare)} MGD before any campus demand.`
    : null;
  const method =
    "Modeled with Max Day: hourly heat rejection, evaporation and blowdown from latent heat, chiller power from outdoor conditions. " +
    "Cap scheduling is a fractional knapsack per day, provably optimal. Plant parameters are planning assumptions; weather is measured " +
    "(Iowa Environmental Mesonet, station KOFP).";

  const copy = () => {
    const text = [
      "Hanover County, Virginia. Draft, October 18, 2026.",
      `Proposed condition: cooling water. ${campus.name} rezoning, ${campus.mw.toLocaleString("en-US")} MW IT load.`,
      "",
      "Condition",
      ...clauses.map((c, i) => `${i + 1}. ${c}`),
      "",
      "Basis",
      basis,
      `Hybrid design: worst day ${mgd(hybrid.maxDayGal)} MGD, annual water ${mgal(hybrid.annualGal)} M gal, electricity ${int(hybrid.annualMWh)} MWh, peak ${fixed(hybrid.peakMW, 1)} MW.`,
      `With condition: worst day ${mgd(plan.maxDayGal)} MGD, annual water ${mgal(plan.annualGal)} M gal, electricity ${int(plan.annualMWh)} MWh, peak ${fixed(plan.peakMW, 1)} MW.`,
      county + (shortfall ? ` ${shortfall}` : ""),
      "",
      "Method",
      method,
      "",
      "Draft for discussion, not legal advice. Generated by Max Day.",
      window.location.href,
    ].join("\n");
    navigator.clipboard?.writeText(text).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 1400);
    });
  };

  return (
    <div className="page">
      <PageHeader
        title="Condition"
        meta={
          <>
            <span>Draft for discussion, not legal advice</span>
            <span className="dim tnum">
              {campus.name}, {campus.mw.toLocaleString("en-US")} MW IT load
            </span>
          </>
        }
        actions={
          <>
            <Button icon={copied ? <Check /> : <Copy />} onClick={copy}>
              {copied ? "Copied" : "Copy text"}
            </Button>
            <Button variant="primary" icon={<Printer />} onClick={() => window.print()}>
              Print
            </Button>
          </>
        }
      />

      <div className="cond-grid">
        <article className="doc" aria-label="Drafted permit condition">
          <div className="doc__top">
            <span>Hanover County, Virginia</span>
            <span>Draft, October 18, 2026</span>
          </div>
          <h2 className="doc__title">Proposed condition: cooling water</h2>
          <p className="doc__subtitle">
            {campus.name} rezoning, {campus.mw.toLocaleString("en-US")} MW IT load
          </p>

          <h3 className="doc__h">Condition</h3>
          <ol className="doc__clauses">
            <li>
              Cooling water use shall not exceed <strong>{capText} gallons</strong> on any calendar day.
            </li>
            <li>{clauses[1]}</li>
            <li>
              The facility shall not exceed a peak electrical demand of <strong>{peakText} MW</strong> to meet the limit in
              condition 1.
            </li>
            <li>{clauses[3]}</li>
          </ol>

          <h3 className="doc__h">Basis</h3>
          <p>{basis}</p>
          <table className="doc__table">
            <thead>
              <tr>
                <th aria-label="Case" />
                <th>Worst day, MGD</th>
                <th>Annual water, M gal</th>
                <th>Electricity, MWh</th>
                <th>Peak, MW</th>
              </tr>
            </thead>
            <tbody>
              <tr>
                <th scope="row">Hybrid design</th>
                <td>{mgd(hybrid.maxDayGal)}</td>
                <td>{mgal(hybrid.annualGal)}</td>
                <td>{int(hybrid.annualMWh)}</td>
                <td>{fixed(hybrid.peakMW, 1)}</td>
              </tr>
              <tr>
                <th scope="row">With condition</th>
                <td>{mgd(plan.maxDayGal)}</td>
                <td>{mgal(plan.annualGal)}</td>
                <td>{int(plan.annualMWh)}</td>
                <td>{fixed(plan.peakMW, 1)}</td>
              </tr>
            </tbody>
          </table>

          <h3 className="doc__h">County system</h3>
          <p>
            {county}
            {shortfall && <span className="doc__alarm"> × {shortfall}</span>}
          </p>

          <h3 className="doc__h">Method</h3>
          <p>{method}</p>

          <footer className="doc__foot">
            <span>Draft for discussion, not legal advice. Generated by Max Day.</span>
            <span className="doc__url">{window.location.href}</span>
          </footer>
        </article>

        <aside className="cond-side">
          <Card title="Inputs">
            <dl className="rows">
              <Row label="Daily cap">{capText} gal</Row>
              <Row label="Peak limit">{peakText} MW</Row>
              <Row label="Annual water, held to the hybrid's">{mgal(hybrid.annualGal)} M gal</Row>
            </dl>
            <Button className="cond-side__btn" icon={<SlidersHorizontal />} onClick={() => set({ view: "plan" })}>
              Adjust in Plan
            </Button>
          </Card>
          <Card title="What the cap does" meta="Against the adiabatic hybrid, modeled">
            <dl className="rows">
              <Row label="Worst day before">
                {mgd(hybrid.maxDayGal)} MGD, {dateLabel(year, hybrid.maxDay)}
              </Row>
              <Row label="Worst day after" tone="amber">
                {mgd(plan.maxDayGal)} MGD
              </Row>
              <Row label="Change">{pctChange(hybrid.maxDayGal, plan.maxDayGal)}</Row>
              <Row label="Annual water">
                {Math.abs(plan.annualGal - hybrid.annualGal) < 5e4 ? "Same" : `${signed((plan.annualGal - hybrid.annualGal) / 1e6, 1)} M gal`}
              </Row>
              <Row label="Electricity">{signed(plan.annualMWh - hybrid.annualMWh)} MWh</Row>
              <Row label="Peak power">{plan.peakMW <= hybrid.peakMW + 0.05 ? `No higher, ${plan.peakMW.toFixed(1)} MW` : `${signed(plan.peakMW - hybrid.peakMW, 1)} MW`}</Row>
            </dl>
          </Card>
        </aside>
      </div>
    </div>
  );
}
